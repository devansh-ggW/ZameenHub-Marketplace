import assert from 'node:assert/strict'
import { MAX_PROPERTY_DOCUMENT_BYTES,detectDocumentFormat,sanitizeDocumentFileName,sanitizeDocumentLabel,sanitizePublicReviewSummary,isPropertyDocumentType,isPropertyDocumentRole } from '../worker/property-documents.ts'
const ascii=value=>new TextEncoder().encode(value)
assert.equal(MAX_PROPERTY_DOCUMENT_BYTES,8*1024*1024)
const pdf=ascii('%PDF-1.7\n1 0 obj\n<< /Type /Catalog >>\nendobj\nxref\n0 1\n0000000000 65535 f\ntrailer\n<< /Size 1 >>\nstartxref\n42\n%%EOF\n')
assert.deepEqual(detectDocumentFormat(pdf,'title.pdf'),{extension:'.pdf',contentType:'application/pdf'})
const jpeg=new Uint8Array(16);jpeg.set([0xff,0xd8,0xff,0xe0,0x00,0x10,0x4a,0x46,0x49,0x46,0x00,0x01],0);jpeg[14]=0xff;jpeg[15]=0xd9
assert.deepEqual(detectDocumentFormat(jpeg,'scan.jpeg'),{extension:'.jpeg',contentType:'image/jpeg'})
const png=new Uint8Array(45);png.set([0x89,0x50,0x4e,0x47,0x0d,0x0a,0x1a,0x0a],0);png.set([0,0,0,13],8);png.set(ascii('IHDR'),12);png.set([0,0,0,1,0,0,0,1,8,2,0,0,0],16);png.set(ascii('IEND'),37);png.set([0xae,0x42,0x60,0x82],41)
assert.deepEqual(detectDocumentFormat(png,'plan.png'),{extension:'.png',contentType:'image/png'})
const webp=new Uint8Array(22);webp.set(ascii('RIFF'),0);new DataView(webp.buffer).setUint32(4,14,true);webp.set(ascii('WEBPVP8 '),8);new DataView(webp.buffer).setUint32(16,2,true);webp.set([1,2],20)
assert.deepEqual(detectDocumentFormat(webp,'record.webp'),{extension:'.webp',contentType:'image/webp'})
assert.equal(detectDocumentFormat(ascii('<html>not a pdf'),'document.pdf'),null)
assert.equal(detectDocumentFormat(ascii('%PDF-1.7\n'),'truncated.pdf'),null)
assert.equal(detectDocumentFormat(jpeg.slice(0,-2),'truncated.jpg'),null)
assert.equal(detectDocumentFormat(png.slice(0,-12),'truncated.png'),null)
const badWebp=webp.slice();new DataView(badWebp.buffer).setUint32(4,999,true)
assert.equal(detectDocumentFormat(badWebp,'broken.webp'),null)
assert.equal(detectDocumentFormat(ascii('%PDF-1.7'),'document.png'),null)
assert.equal(detectDocumentFormat(new Uint8Array(0),'document.pdf'),null)
assert.equal(detectDocumentFormat(new Uint8Array(MAX_PROPERTY_DOCUMENT_BYTES+1),'document.pdf'),null)
assert.equal(detectDocumentFormat(ascii('%PDF-1.7'),'document.svg'),null)
assert.equal(sanitizeDocumentFileName('C:\\fakepath\\registry.pdf')?.basename,'registry.pdf')
assert.equal(sanitizeDocumentFileName('no-extension'),null)
assert.equal(sanitizeDocumentLabel('   ','Sale deed'),'Sale deed')
assert.equal(sanitizeDocumentLabel('Approved <script> plan','Plan'),'Approved script plan')
assert.equal(sanitizeDocumentLabel('a'.repeat(101),'Plan'),null)
assert.equal(sanitizeDocumentLabel('A\n\tB','Plan'),'AB')
assert.equal(sanitizePublicReviewSummary('Compared the property ID and issue date with the public registry entry.'),'Compared the property ID and issue date with the public registry entry.')
assert.equal(sanitizePublicReviewSummary('Contact seller at owner@example.com for more.'),null)
assert.equal(sanitizePublicReviewSummary('PAN ABCDE1234F was included in the note.'),null)
assert.equal(sanitizePublicReviewSummary('Aadhaar 1234 5678 9012 appeared.'),null)
assert.equal(sanitizePublicReviewSummary('Call owner at +91 98765 43210.'),null)
assert.equal(sanitizePublicReviewSummary('See https://private.example/document.pdf'),null)
assert.equal(sanitizePublicReviewSummary('Too short'),null)
assert.equal(isPropertyDocumentType('sale_deed'),true)
assert.equal(isPropertyDocumentType('administrator'),false)
assert.equal(isPropertyDocumentRole('public_copy'),true)
assert.equal(isPropertyDocumentRole('private_original'),true)
assert.equal(isPropertyDocumentRole('public'),false)
console.log('Property-document format tests passed. Structural markers reject common truncation but do not provide full parsing, malware scanning or authenticity verification.')
